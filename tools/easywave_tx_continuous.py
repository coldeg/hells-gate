"""Current 111-byte transport model. Offline only; no preconfigured RF commands."""
import argparse
import json
import math
from pathlib import Path
from easywave_tx_frame import integrity_variant, manchester_encode, word_bits

ROOT = Path(__file__).resolve().parents[1]
IDENTITY = 'NIKOBUS_HELTEC_EASYWAVE_GATEWAY_V8_7_LEARNED'
TRANSPORT_BPS, POWER_DBM = 8006, 14
REPEATS, DATA_CHIPS, HOLD_CHIPS = 3, 66, 8
BYTES = 111
AIRTIME_US = math.ceil(BYTES * 8e6 / TRANSPORT_BPS)
CYCLE_US = math.ceil(37 * 8e6 / TRANSPORT_BPS)


def payload(word, tail):
    """Encode an explicit complete frame; this function does not authorize RF use."""
    integrity_variant(word)
    if type(tail) is not int or tail not in (0, 1):
        raise ValueError('An explicit observed tail of 0 or 1 is required')
    frame = bytes(0xF0 if bit else 0x0F for bit in word_bits(word) + [tail])
    return (frame + bytes(4)) * REPEATS


def verify():
    # Deliberately fictional prefixes; checks describe encoding, not receiver pairing.
    from easywave_tx_frame import crc8
    for serial in (0x012345, 0x023456):
        prefix = (serial << 2).to_bytes(3, 'big')
        word = int.from_bytes(prefix + bytes([crc8(prefix) ^ 0xB4]), 'big')
        for tail in (0, 1):
            encoded = payload(word, tail)
            chips = manchester_encode(word_bits(word) + [tail])
            expected = bytes(0xFF if chip else 0 for chip in chips)
            # Four transport samples per chip, two chips per source bit.
            expanded = bytes(0xF0 if chips[i] else 0x0F for i in range(0, 66, 2))
            assert len(expected) == 66 and expanded == encoded[:33]
            assert len(encoded) == BYTES and encoded[32] == (0xF0 if tail else 0x0F)
            assert encoded[33:37] == bytes(4)
            assert encoded[:37] == encoded[37:74] == encoded[74:]
    assert AIRTIME_US == 110917


def generate():
    verify()
    # An empty native table is intentional: third-party installations learn their own
    # received commands. Synthetic test fixtures never provision production firmware.
    header = '\n'.join([
        '// Generated by tools/easywave_tx_continuous.py --generate; no household data.',
        '#pragma once', '#include <stdint.h>', '#include <stddef.h>', '#include <array>',
        'namespace easywave4x {', f'constexpr const char* identity = "{IDENTITY}";',
        f'constexpr uint8_t physicalChips = {DATA_CHIPS}, holdChips = {HOLD_CHIPS};',
        f'constexpr uint8_t repeats = {REPEATS};', f'constexpr size_t payloadBytes = {BYTES};',
        f'constexpr int8_t powerDbm = {POWER_DBM};',
        f'constexpr float bitRateKbps = {TRANSPORT_BPS / 1000:.6f}F;',
        f'constexpr uint32_t framePeriodUs = {CYCLE_US}, nominalFrameAirtimeUs = {CYCLE_US};',
        f'constexpr uint32_t nominalBurstAirtimeUs = {AIRTIME_US};',
        'struct Frame { uint32_t word; bool inverted; uint8_t payload[payloadBytes]; };',
        'constexpr std::array<Frame, 0> frames{};',
        'inline const uint8_t* payloadFor(uint32_t word, bool inverted = false) {',
        '  for (const Frame& f : frames) if (f.word == word && f.inverted == inverted) return f.payload;',
        '  return nullptr;', '}',
        'static_assert(payloadBytes * 8 == (physicalChips + holdChips) * 4 * repeats, "complete burst");',
        '}', ''])
    (ROOT / 'src/easywave_tx_continuous_generated.h').write_text(header, encoding='utf-8')
    timing = dict(firmware=IDENTITY, burst_airtime_us=AIRTIME_US,
                  physical_chips_per_repeat=DATA_CHIPS, hold_chips=HOLD_CHIPS,
                  repeats=REPEATS, radio_calls=1, transport_bitrate_bps=TRANSPORT_BPS,
                  payload_bytes=BYTES)
    (ROOT / 'addon/easywave_gateway/tx_timing.json').write_text(json.dumps(timing, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    args = parser.parse_args()
    verify()
    if args.generate:
        generate()
    print(f'CONTINUOUS_VERIFIED bytes={BYTES} airtime_us={AIRTIME_US} radio_calls=1 native_commands=0')
