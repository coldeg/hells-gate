"""Build/check a self-contained local card from readable sources and language packs.

I keep this build free of npm, network access and frontend runtime dependencies.
Adding a language means adding a JSON pack with the same keys and placeholders.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / 'frontend'


def bundle():
    packs = {path.stem: json.loads(path.read_text(encoding='utf-8'))
             for path in sorted((FRONTEND/'translations').glob('*.json'))}
    reference = packs['en']
    for language, pack in packs.items():
        if pack.keys() != reference.keys():
            raise ValueError(f'{language}: translation keys differ from English')
        for key, value in pack.items():
            if not isinstance(value, str) or not value:
                raise ValueError(f'{language}.{key}: missing text')
            placeholders = lambda text: set(re.findall(r'\{([a-z_]+)\}', text))
            if placeholders(value) != placeholders(reference[key]):
                raise ValueError(f'{language}.{key}: placeholders differ')
    runtime = (FRONTEND/'src/i18n.js').read_text(encoding='utf-8')
    component = (FRONTEND/'src/card.js').read_text(encoding='utf-8')
    styles = (FRONTEND/'src/card.css').read_text(encoding='utf-8')
    used = set(re.findall(r"this\.t\(['\"]([^'\"]+)", component))
    if used - reference.keys():
        raise ValueError('Unknown translation keys: ' + ', '.join(sorted(used-reference.keys())))
    header = '// Generated by tools/build_frontend.py. Edit frontend/src/ and translations/, not this bundle.\n'
    return (header + "(() => {\n'use strict';\nconst HG_TRANSLATIONS = "
            + json.dumps(packs,ensure_ascii=False,indent=2) + ';\nconst HG_CARD_CSS = '
            + json.dumps(styles,ensure_ascii=False) + ';\n' + runtime + '\n' + component + '\n})();\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = bundle()
    target = FRONTEND/'hells-gate-card.js'
    if args.check:
        if target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Frontend bundle is stale; run python tools/build_frontend.py')
    else:
        target.write_bytes(expected.encode('utf-8'))
    print('FRONTEND_BUNDLE_VERIFIED' if args.check else 'FRONTEND_BUNDLE_BUILT')


if __name__ == '__main__':
    main()
